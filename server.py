class Err(Exception):
    pass


class PostgresConnection:
    """Kleine adapter zodat de bestaande queries zowel SQLite als PostgreSQL gebruiken."""
    def __init__(self, connection):
        self.connection = connection

    def execute(self, sql, params=()):
        return self.connection.execute(sql.replace("?", "%s"), params)

    def commit(self):
        self.connection.commit()

    def rollback(self):
        self.connection.rollback()

    def close(self):
        self.connection.close()


def open_database():
    if DATABASE_URL:
        import psycopg
        from psycopg.rows import dict_row
        connection = psycopg.connect(DATABASE_URL, row_factory=dict_row, autocommit=True, connect_timeout=15)
        return PostgresConnection(connection)
    SQLITE_DB.parent.mkdir(parents=True, exist_ok=True)
    connection = sqlite3.connect(SQLITE_DB, timeout=15, isolation_level=None)
    connection.row_factory = sqlite3.Row
    connection.execute("PRAGMA foreign_keys=ON")
    return connection


def insert_id(db, sql, params):
    if DATABASE_URL:
        return db.execute(sql + " RETURNING id", params).fetchone()["id"]
    return db.execute(sql, params).lastrowid


def is_unique_error(error):
    return isinstance(error, sqlite3.IntegrityError) or getattr(error, "sqlstate", None) == "23505"


def now():
    return datetime.now(TZ).strftime("%Y-%m-%dT%H:%M")


def hash_pw(password, salt=None):
    salt = salt or secrets.token_hex(8)
    return salt + ":" + hashlib.pbkdf2_hmac("sha256", password.encode(), salt.encode(), 200_000).hex()


def text(d, key, lo, hi):
    value = d.get(key)
    if not isinstance(value, str) or not lo <= len(value.strip()) <= hi:
        raise Err(f"Het veld '{key}' moet {lo} tot {hi} tekens bevatten.")
    return value.strip()


def activity_values(d):
    values = {"title": text(d, "title", 3, 90), "meeting_point": text(d, "meeting_point", 3, 160), "description": text(d, "description", 20, 2400)}
    for key, allowed in (("sport", SPORTS), ("district", DISTRICTS), ("level", LEVELS)):
        if d.get(key) not in allowed:
            raise Err("Kies een geldige sport, wijk en niveau.")
        values[key] = d[key]
    capacity, start = d.get("capacity"), d.get("starts_at")
    if type(capacity) is not int or not 2 <= capacity <= 200:
        raise Err("Kies een maximum van 2 tot 200 deelnemers.")
    if not isinstance(start, str) or not re.fullmatch(r"\d{4}-\d\d-\d\dT\d\d:\d\d", start):
        raise Err("Kies een geldige datum en tijd.")
    if start <= now():
        raise Err("Kies een datum en tijd in de toekomst.")
    return {**values, "capacity": capacity, "starts_at": start}


def initialize_database():
    db = open_database()
    try:
        schema = POSTGRES_SCHEMA if DATABASE_URL else SQLITE_SCHEMA
        for statement in schema.split(";"):
            if statement.strip():
                db.execute(statement)
        count = db.execute("SELECT COUNT(*) AS n FROM activities").fetchone()["n"]
        if not count:
            for day, (title, sport, district, level, capacity, description, clock) in enumerate(EXAMPLES, 1):
                start = (datetime.now(TZ) + timedelta(days=day)).strftime("%Y-%m-%d") + "T" + clock
                db.execute("""INSERT INTO activities(title,sport,district,meeting_point,level,starts_at,capacity,description,is_example)
                              VALUES(?,?,?,?,?,?,?,?,1)""",
                           (title, sport, district, "Dit is een voorbeeldactiviteit. Er is geen echte bijeenkomst gepland.", level, start, capacity, description))
    finally:
        db.close()


class Handler(BaseHTTPRequestHandler):
    def log_message(self, fmt, *args):
        print("%s - %s" % (self.address_string(), fmt % args))

    def reply(self, data, code=200, ctype="application/json"):
        body = data if isinstance(data, bytes) else json.dumps(data, ensure_ascii=False).encode()
        self.send_response(code)
        self.send_header("Content-Type", ctype)
        self.send_header("Content-Length", str(len(body)))
        self.send_header("Cache-Control", "no-store")
        self.send_header("X-Content-Type-Options", "nosniff")
        if getattr(self, "cookie", None):
            self.send_header("Set-Cookie", self.cookie)
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self):
        self.cookie = None
        path = self.path.split("?")[0]
        if path == "/health":
            return self.reply({"status": "ok"})
        if path.startswith("/api/"):
            return self.api(path)
        name = "index.html" if path == "/" else path.lstrip("/")
        file = (ROOT / name).resolve()
        if not file.is_file() or not (name in PUBLIC or file.parent == ROOT / "assets"):
            return self.reply({"error": "Deze pagina bestaat niet."}, 404)
        return self.reply(file.read_bytes(), 200, TYPES.get(file.suffix, "application/octet-stream"))

    do_POST = do_PUT = do_GET

    def api(self, path):
        try:
            size = int(self.headers.get("Content-Length") or 0)
            data = json.loads(self.rfile.read(min(size, 30000)) or "{}")
            if not isinstance(data, dict):
                raise ValueError
        except (ValueError, json.JSONDecodeError):
            return self.reply({"error": "Het verzoek bevat geen geldige gegevens."}, 400)
        db = None
        try:
            db = open_database()
            if self.command != "GET":
                db.execute("BEGIN")
            result = self.route(db, path, data)
            db.commit()
            if isinstance(result, tuple):
                return self.reply(*result)
            return self.reply(result)
        except Err as error:
            if db:
                db.rollback()
            return self.reply({"error": str(error)}, getattr(error, "status", 400))
        except Exception as error:
            if db:
                db.rollback()
            print(f"Fout bij databaseverzoek: {type(error).__name__}: {error}")
            return self.reply({"error": "Opslaan is niet gelukt. Probeer het opnieuw."}, 503)
        finally:
            if db:
                db.close()

    def route(self, db, path, data):
        query = lambda sql, *args: [dict(row) for row in db.execute(sql, args)]
        one = lambda sql, *args: (query(sql, *args) or [None])[0]
        sid = SimpleCookie(self.headers.get("Cookie", "")).get("sid")
        user = one("SELECT u.id,u.name,u.email FROM sessions s JOIN users u ON u.id=s.user_id WHERE s.token=?", sid.value) if sid else None

        def need():
            if not user:
                err = Err("Log eerst in om verder te gaan.")
                err.status = 401
                raise err

        def activity(activity_id):
            result = one(ACTIVITY + " WHERE a.id=?", activity_id)
            if not result:
                err = Err("Deze activiteit bestaat niet meer.")
                err.status = 404
                raise err
            return result

        def mine(activity_id):
            need()
            result = activity(activity_id)
            if result["organizer_id"] != user["id"]:
                err = Err("Je kunt alleen je eigen activiteiten beheren.")
                err.status = 403
                raise err
            return result

        def sign_in(user_id):
            token = secrets.token_urlsafe(32)
            db.execute("INSERT INTO sessions VALUES(?,?)", (token, user_id))
            secure = self.headers.get("X-Forwarded-Proto", "").split(",")[0] == "https" or bool(os.environ.get("RENDER"))
            self.cookie = f"sid={token}; Path=/; HttpOnly; SameSite=Lax; Max-Age=604800" + ("; Secure" if secure else "")
            return {"user": one("SELECT id,name,email FROM users WHERE id=?", user_id)}

        shape = re.sub(r"\d+", "#", path)
        ids = [int(value) for value in re.findall(r"\d+", path)]
        route = f"{self.command} {shape}"

        if route == "GET /api/session":
            return {"user": user}
        if route == "POST /api/register":
            name = text(data, "name", 2, 80)
            email = text(data, "email", 5, 254).lower()
            password = text(data, "password", 10, 128)
            if not EMAIL.fullmatch(email):
                raise Err("Vul een geldig e-mailadres in.")
            try:
                uid = insert_id(db, "INSERT INTO users(name,email,password) VALUES(?,?,?)", (name, email, hash_pw(password)))
            except Exception as error:
                if is_unique_error(error):
                    err = Err("Er bestaat al een account met dit e-mailadres.")
                    err.status = 409
                    raise err
                raise
            return sign_in(uid), 201
        if route == "POST /api/login":
            account = one("SELECT * FROM users WHERE email=?", text(data, "email", 5, 254).lower())
            if not account or not secrets.compare_digest(hash_pw(text(data, "password", 1, 128), account["password"].split(":")[0]), account["password"]):
                err = Err("Je e-mailadres of wachtwoord klopt niet.")
                err.status = 401
                raise err
            return sign_in(account["id"])
        if route == "POST /api/logout":
            if sid:
                db.execute("DELETE FROM sessions WHERE token=?", (sid.value,))
            secure = self.headers.get("X-Forwarded-Proto", "").split(",")[0] == "https" or bool(os.environ.get("RENDER"))
            self.cookie = "sid=; Path=/; Max-Age=0; HttpOnly" + ("; Secure" if secure else "")
            return {"user": None}

        if route == "GET /api/activities":
            return {"activities": query(ACTIVITY + " WHERE a.status='active' AND a.starts_at>? ORDER BY a.starts_at", now())}
        if route == "GET /api/activities/#":
            return {"activity": activity(ids[0])}
        if route == "POST /api/activities":
            need()
            values = activity_values(data)
            columns = ",".join(values)
            placeholders = ",".join("?" for _ in values)
            activity_id = insert_id(db, f"INSERT INTO activities({columns},organizer_id) VALUES({placeholders},?)", (*values.values(), user["id"]))
            return {"activity": activity(activity_id)}, 201
        if route == "PUT /api/activities/#":
            existing, values = mine(ids[0]), activity_values(data)
            if existing["status"] != "active":
                err = Err("Een geannuleerde activiteit kun je niet meer wijzigen.")
                err.status = 409
                raise err
            if values["capacity"] < existing["participants"]:
                raise Err("Het maximum mag niet lager zijn dan het aantal aanmeldingen.")
            db.execute(f"UPDATE activities SET {','.join(key + '=?' for key in values)} WHERE id=?", (*values.values(), existing["id"]))
            return {"activity": activity(existing["id"])}
        if route == "POST /api/activities/#/cancel":
            mine(ids[0])
            db.execute("UPDATE activities SET status='cancelled' WHERE id=?", (ids[0],))
            return {"ok": True}
        if route == "GET /api/activities/#/participants":
            existing = mine(ids[0])
            return {"title": existing["title"], "participants": query("SELECT name,email FROM registrations WHERE activity_id=? ORDER BY created_at", existing["id"])}
        if route == "POST /api/activities/#/join":
            name, email = text(data, "name", 2, 80), text(data, "email", 5, 254).lower()
            if not EMAIL.fullmatch(email):
                raise Err("Vul een geldig e-mailadres in.")
            if data.get("consent") is not True:
                raise Err("Geef toestemming om je aanmelding met de organisator te delen.")
            existing = activity(ids[0])
            if existing["status"] != "active" or existing["starts_at"] <= now():
                err = Err("Voor deze activiteit kun je je niet meer aanmelden.")
                err.status = 409
                raise err
            if one("SELECT 1 FROM registrations WHERE activity_id=? AND email=?", existing["id"], email):
                err = Err("Dit e-mailadres is al aangemeld voor deze activiteit.")
                err.status = 409
                raise err
            if existing["participants"] >= existing["capacity"]:
                err = Err("Deze activiteit zit inmiddels vol. Kies een andere activiteit.")
                err.status = 409
                raise err
            token = secrets.token_urlsafe(32)
            registration_id = insert_id(db, "INSERT INTO registrations(activity_id,user_id,name,email,token) VALUES(?,?,?,?,?)",
                                        (existing["id"], user and user["id"], name, email, hashlib.sha256(token.encode()).hexdigest()))
            scheme = self.headers.get("X-Forwarded-Proto", "https" if os.environ.get("RENDER") else "http").split(",")[0]
            cancel_url = f"{scheme}://{self.headers.get('Host')}/#/afmelden/{registration_id}/{token}"
            return {"cancel_url": cancel_url, "activity": activity(existing["id"])}, 201
        if route == "POST /api/registrations/#/cancel":
            registration = one("SELECT * FROM registrations WHERE id=?", ids[0])
            token = str(data.get("token", ""))
            if not registration:
                err = Err("Deze aanmelding bestaat niet meer. Mogelijk heb je je al afgemeld.")
                err.status = 404
                raise err
            owner = user and registration["user_id"] == user["id"]
            if not owner and not (token and secrets.compare_digest(registration["token"], hashlib.sha256(token.encode()).hexdigest())):
                err = Err("Deze afmeldlink is ongeldig.")
                err.status = 403
                raise err
            db.execute("DELETE FROM registrations WHERE id=?", (ids[0],))
            return {"ok": True}
        if route == "GET /api/my-activities":
            need()
            return {"hosted": query(ACTIVITY + " WHERE a.organizer_id=? ORDER BY a.starts_at DESC", user["id"]),
                    "joined": query("""SELECT r.id registration_id, a.id, a.title, a.district, a.starts_at, a.status FROM registrations r
                                      JOIN activities a ON a.id=r.activity_id WHERE r.user_id=? ORDER BY a.starts_at""", user["id"])}
        raise Err("Deze actie is niet beschikbaar.")


